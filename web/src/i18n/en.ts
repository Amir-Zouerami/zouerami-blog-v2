/** Same shape as `en`, with string literals widened so other locales can translate them. */
type Widen<T> = T extends string
  ? string
  : T extends (infer U)[]
    ? Widen<U>[]
    : T extends (...a: infer A) => infer R
      ? (...a: A) => R
      : { [K in keyof T]: Widen<T[K]> };

export type Dict = Widen<typeof en>;
